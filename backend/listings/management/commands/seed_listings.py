class Command(BaseCommand):
    help = 'Seed the database with realistic Nepal tourism listings'

    def add_arguments(self, parser):
        parser.add_argument(
            '--count', type=int, default=0,
            help='Number of listings to seed (default: all)',
        )
        parser.add_argument(
            '--flush', action='store_true',
            help='Delete all previously seeded data before seeding',
        )
        parser.add_argument(
            '--dry-run', action='store_true',
            help='Preview what would be created without writing to the DB',
        )

    def handle(self, *args, **options):
        count = options['count'] or len(LISTINGS)
        flush = options['flush']
        dry_run = options['dry_run']

        selected = LISTINGS[:count]
        self.stdout.write(f'{len(selected)} listings to seed')

        if dry_run:
            self._preview(selected)
            return

        with transaction.atomic():
            if flush:
                self._flush_seeded_data()

            hosts = self._create_hosts()

            created = 0
            for entry in selected:
                category = entry['category']
                defaults = CATEGORY_DEFAULTS[category]

                host_idx = defaults['host_idx']
                # 20% chance of being assigned to a different host for variety
                if random.random() < 0.2:
                    host_idx = random.randint(0, len(hosts) - 1)

                listing = self._create_listing(entry, defaults, hosts[host_idx])
                if listing:
                    image_count = self._attach_images(listing, category)
                    if image_count:
                        listing.is_bookable = True
                        listing.save(update_fields=['is_bookable'])
                    self._create_slots(listing)
                    created += 1

            self.stdout.write(self.style.SUCCESS(
                f'Successfully seeded {created} listings across {len(hosts)} hosts'
            ))

    def _preview(self, entries: list[dict]):
        from collections import Counter
        cat_counts = Counter(e['category'] for e in entries)
        dest_counts = Counter(e['destination'] for e in entries)

        self.stdout.write('\n=== DRY RUN PREVIEW ===')
        self.stdout.write(f'Total listings: {len(entries)}\n')
        self.stdout.write('By category:')
        for cat, n in cat_counts.most_common():
            self.stdout.write(f'  {cat}: {n}')
        self.stdout.write('\nTop destinations:')
        for dest, n in dest_counts.most_common(15):
            self.stdout.write(f'  {dest}: {n}')
        self.stdout.write(f'\n{len(SEED_HOSTS)} hosts would be created')
        self.stdout.write('2-4 images per listing from seed_images/')
        self.stdout.write('3-8 activity slots per listing (next 30-60 days)')

    def _flush_seeded_data(self):
        seed_emails = [h['email'] for h in SEED_HOSTS]
        deleted = Account.objects.filter(email__in=seed_emails)
        count = deleted.count()
        if count:
            deleted.delete()
            self.stdout.write(f'Flushed {count} seeded host accounts and all related data')
        else:
            self.stdout.write('No previously seeded data found')

    def _create_hosts(self) -> list:
        hosts = []
        for h in SEED_HOSTS:
            account, created = Account.objects.get_or_create(
                email=h['email'],
                defaults={
                    'first_name': h['first_name'],
                    'last_name': h['last_name'],
                    'role': 'host',
                    'is_active': True,
                    'has_completed_onboarding': True,
                    'onboarding_step': 5,
                },
            )
            if created:
                account.set_password('Hello@123')
                account.save()
                self.stdout.write(f'  Created host: {h["email"]}')
            else:
                self.stdout.write(f'  Exists: {h["email"]}')

            host_detail, _ = HostDetail.objects.get_or_create(
                user=account,
                defaults={
                    'business_name': h['business_name'],
                    'about_service': h['about_service'],
                    'verification_status': 'approved',
                },
            )
            hosts.append(host_detail)
        return hosts

    def _get_text_value(self, entry: dict, key: str, fallback: str = '') -> str:
        value = entry.get(key)
        if isinstance(value, str):
            value = value.strip()
        return value or fallback

    def _get_list_value(self, entry: dict, key: str, fallback: list | None = None) -> list:
        value = entry.get(key)
        if value:
            return list(value)
        return list(fallback or [])

    def _create_listing(self, entry: dict, defaults: dict, host_detail) -> Listing | None:
        # Duration handling
        dur_type = entry.get('duration_type', 'full_day')
        duration_days = entry.get('duration_days', 1)
        duration_nights = entry.get('duration_nights', 0)
        avg_hours = Decimal('0')

        if dur_type == 'hourly':
            duration_days = 0
            duration_nights = 0
            avg_hours = Decimal(entry.get('average_duration_hours', '4'))
        elif dur_type == 'full_day':
            duration_days = entry.get('duration_days', 1)
            duration_nights = 0

        listing = Listing(
            host=host_detail,
            title=entry['title'],
            description=entry['description'],
            destination=entry['destination'],
            location=entry['location'],
            category=entry['category'],
            activity_type=entry['activity_type'],
            difficulty_level=entry.get('difficulty_level', 'easy'),
            ideal_for=self._get_list_value(entry, 'ideal_for', ['solo', 'couples']),
            price_per_person=Decimal(str(entry['price_per_person'])),
            duration_type=dur_type,
            duration_days=duration_days,
            duration_nights=duration_nights,
            tags=self._get_list_value(entry, 'tags'),
            what_to_bring=self._get_text_value(entry, 'what_to_bring', defaults['what_to_bring']),
            requirements=self._get_text_value(entry, 'requirements', defaults['requirements']),
            inclusions=self._get_list_value(entry, 'inclusions', defaults['inclusions']),
            exclusions=self._get_list_value(entry, 'exclusions', defaults['exclusions']),
            cancellation_policy=entry.get('cancellation_policy', 'moderate'),
            languages_offered=self._get_list_value(entry, 'languages_offered', defaults['languages']),
            best_seasons=self._get_list_value(entry, 'best_seasons', ['year_round']),
            is_bookable=False,
            is_active=True,
            max_group_size=entry.get('max_group_size', 10),
            min_group_size=entry.get('min_group_size', 1),
            instant_booking=entry.get('instant_booking', True),
            rating_average=Decimal(entry.get('rating_average', '0')),
            rating_count=entry.get('rating_count', 0),
            booking_count=entry.get('booking_count', 0),
        )

        if dur_type == 'hourly' and avg_hours > 0:
            listing.average_duration_hours = avg_hours

        listing.save()
        return listing

    def _attach_images(self, listing: Listing, category: str) -> int:
        folder_name = CATEGORY_TO_IMAGE_FOLDER.get(category, 'culture')
        source_dir = SEED_IMAGES_DIR / folder_name

        if not source_dir.exists():
            return 0

        available = [
            f for f in source_dir.iterdir()
            if f.is_file() and f.suffix.lower() in ('.jpg', '.jpeg', '.png', '.webp')
        ]
        if not available:
            return 0

        num_images = min(random.randint(2, 4), len(available))
        chosen = random.sample(available, num_images)

        for i, src_path in enumerate(chosen):
            with src_path.open('rb') as image_fp:
                source_file = File(image_fp, name=src_path.name)
                compressed_image = compress_image(source_file, output_format="WEBP")
                thumbnail_image = create_thumbnail(source_file, output_format="WEBP")

            ListingImage.objects.create(
                listing=listing,
                image=compressed_image,
                thumbnail=thumbnail_image,
                is_primary=(i == 0),
                caption=f'{listing.title} - Image {i + 1}',
                order=i,
            )

        return len(chosen)

    def _create_slots(self, listing: Listing):
        today = date.today()
        num_slots = random.randint(3, 8)

        if listing.duration_type == DurationType.MULTI_DAY:
            for _ in range(num_slots):
                start = today + timedelta(days=random.randint(7, 60))
                end = start + timedelta(days=listing.duration_days - 1)
                ActivitySlot.objects.get_or_create(
                    listing=listing,
                    start_date=start,
                    end_date=end,
                    start_time=None,
                    defaults={
                        'capacity': listing.max_group_size,
                        'is_active': True,
                    },
                )
        elif listing.duration_type == DurationType.HOURLY:
            hours_val = float(listing.average_duration_hours or 4)
            time_options = [
                (time(7, 0), time(7 + int(hours_val), 0)),
                (time(9, 0), time(9 + int(hours_val), 0)),
                (time(10, 0), time(10 + int(hours_val), 0)),
                (time(14, 0), time(min(14 + int(hours_val), 23), 0)),
            ]
            for _ in range(num_slots):
                slot_date = today + timedelta(days=random.randint(3, 45))
                start_t, end_t = random.choice(time_options)
                ActivitySlot.objects.get_or_create(
                    listing=listing,
                    start_date=slot_date,
                    end_date=slot_date,
                    start_time=start_t,
                    defaults={
                        'end_time': end_t,
                        'capacity': listing.max_group_size,
                        'is_active': True,
                    },
                )
        else:  # FULL_DAY
            for _ in range(num_slots):
                slot_date = today + timedelta(days=random.randint(3, 45))
                ActivitySlot.objects.get_or_create(
                    listing=listing,
                    start_date=slot_date,
                    end_date=slot_date,
                    start_time=None,
                    defaults={
                        'capacity': listing.max_group_size,
                        'is_active': True,
                    },
                )
